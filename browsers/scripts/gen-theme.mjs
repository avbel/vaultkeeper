import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SLINT_PATH = resolve(here, "../../app/ui/theme.slint");
export const CSS_PATH = resolve(here, "../src/ui/theme.css");

const TOKEN =
  /^\s*out property <color> ([a-z0-9-]+):\s*dark \? (#[0-9A-Fa-f]{6,8}) : (#[0-9A-Fa-f]{6,8});/;

export function parseTokens(slint) {
  const tokens = [];
  for (const line of slint.split("\n")) {
    const m = TOKEN.exec(line);
    if (m) {
      tokens.push({ name: m[1], dark: m[2].toUpperCase(), light: m[3].toUpperCase() });
    }
  }
  return tokens;
}

// Alpha values mirror the `with-alpha` calls in theme.slint; update both together.
const DERIVED = {
  light: [
    "--hover-alpha: 5%",
    "--selection-alpha: 12%",
    "--selection-hover-alpha: 16%",
    "--border-subtle-alpha: 8%",
  ],
  dark: [
    "--hover-alpha: 7%",
    "--selection-alpha: 20%",
    "--selection-hover-alpha: 26%",
    "--border-subtle-alpha: 8%",
  ],
};

const HAND_WRITTEN = `
/* Hand-written tokens. Alphas copy the with-alpha() values of app/ui/theme.slint. */
:root {
  ${DERIVED.light.join(";\n  ")};
  --hover: color-mix(in srgb, var(--text) var(--hover-alpha), transparent);
  --selection: color-mix(in srgb, var(--accent) var(--selection-alpha), transparent);
  --selection-hover: color-mix(in srgb, var(--accent) var(--selection-hover-alpha), transparent);
  --border-subtle: color-mix(in srgb, var(--text) var(--border-subtle-alpha), transparent);
  --font-meta: 11px;
  --font-hint: 12px;
  --font-body: 13px;
  --font-title: 17px;
  --control-height: 28px;
  --field-height: 32px;
  --radius-control: 6px;
  --radius-popup: 10px;
  --gap: 8px;
  --padding: 12px;
  --font: -apple-system, system-ui, sans-serif;
  --mono: Menlo, monospace;
}
:root[data-theme="dark"] {
  ${DERIVED.dark.join(";\n  ")};
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    ${DERIVED.dark.join(";\n    ")};
  }
}
`;

function block(selector, tokens, pick, indent = "") {
  const lines = tokens.map((t) => `${indent}  --${t.name}: ${pick(t)};`);
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`;
}

export function generateCss(slint) {
  const tokens = parseTokens(slint);
  if (tokens.length === 0) {
    throw new Error("no color tokens found in theme.slint");
  }
  return [
    "/* Generated by scripts/gen-theme.mjs from app/ui/theme.slint. Do not edit by hand. */",
    block(":root", tokens, (t) => t.light),
    block(':root[data-theme="dark"]', tokens, (t) => t.dark),
    "@media (prefers-color-scheme: dark) {\n" +
      block(':root:not([data-theme="light"])', tokens, (t) => t.dark, "  ") +
      "\n}",
    HAND_WRITTEN,
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(CSS_PATH, generateCss(readFileSync(SLINT_PATH, "utf8")));
  console.log(`wrote ${CSS_PATH}`);
}
